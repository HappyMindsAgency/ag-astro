export default function customLabel(label: string, lang: Locale = 'it', values: Record<string, string | number> = {}): string {
  const text = lang === 'en' ? english[label] ?? label : label;
  return text.replace(/\{(\w+)\}/g, (match, key) => values[key] === undefined ? match : String(values[key]));
}

export function resultCount(count: number, lang: Locale): string {
  return customLabel(count === 1 ? '{count} risultato' : '{count} risultati', lang, { count });
}

export function documentCount(count: number, lang: Locale): string {
  return customLabel(count === 1 ? '{count} documento' : '{count} documenti', lang, { count });
}
